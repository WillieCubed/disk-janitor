#!/usr/bin/env python3
"""Scoped build entrypoints. Admission and execution remain in the existing guard."""
import sys
if sys.version_info < (3, 10):
    raise SystemExit('disk-janitor: Python 3.10 or newer is required; this is ' + sys.version.split()[0])
import argparse
import fcntl
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import stat
import subprocess

import jobs

# Interpreter and shell entrypoints are deliberately absent: wrapping them would
# recursively intercept the scheduler itself and change unrelated shell work.
TOOLS = ('cargo', 'rustc', 'gradle', 'gradlew', 'xcodebuild', 'swift', 'swiftc',
         'pnpm', 'npm', 'yarn', 'bun', 'make', 'gmake', 'cmake', 'ninja',
         'pytest', 'py.test', 'tsc', 'vitest', 'jest')
SHELLS = ('.zshenv', '.zprofile', '.zshrc', '.bashrc', '.bash_profile')
BEGIN = '# >>> disk-janitor build coverage >>>'
END = '# <<< disk-janitor build coverage <<<'


def home_path():
    path = Path(os.environ.get('DISK_JANITOR_HOME', str(Path.home() / '.disk-janitor')))
    if path.is_symlink():
        raise ValueError('coverage home must not be a symlink')
    return path.resolve()


def strip_block(content):
    start = content.find(BEGIN + '\n')
    if start < 0:
        return content
    end = content.find(END + '\n', start)
    if end < 0:
        raise ValueError('incomplete managed shell coverage block; preserve and inspect it')
    return content[:start] + content[end + len(END) + 1:]


def install_shell():
    home = home_path()
    for name in SHELLS:
        profile = Path.home() / name
        if profile.is_symlink():
            raise ValueError('shell profile is a symlink; preserve it: ' + str(profile))
    shims = home / 'shims'
    if shims.is_symlink():
        raise ValueError('coverage shim directory must not be a symlink')
    shims.mkdir(parents=True, exist_ok=True, mode=0o700)
    shims.chmod(0o700)
    current = home / 'current' / 'coverage.py'
    module = current if current.is_file() else Path(__file__).resolve()
    resolver = ('import os,sys; p=os.path.realpath(sys.argv[1]); '
                "os.execv(sys.executable,[sys.executable,'-B',p,*sys.argv[2:]])")
    shim_body = ('#!/bin/sh\nexec ' + shlex.quote(sys.executable) + ' -B -c ' +
                 shlex.quote(resolver) + ' ' + shlex.quote(str(module)) + ' shim "$0" "$@"\n')
    for name in TOOLS:
        path = shims / name
        if path.is_symlink():
            raise ValueError('coverage shim must not be a symlink: ' + name)
        path.write_text(shim_body)
        path.chmod(0o700)
    state = home / 'state' / 'coverage-shell'
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    quoted = shlex.quote(str(shims))
    block = (BEGIN + '\nif [ -d ' + quoted + ' ]; then\n'
             '  case "$PATH" in\n    ' + quoted + ':*) ;;\n'
             '    *) export PATH=' + quoted + ':"$PATH" ;;\n  esac\nfi\n' + END + '\n')
    for name in SHELLS:
        profile = Path.home() / name
        if profile.is_symlink():
            raise ValueError('shell profile is a symlink; preserve it: ' + str(profile))
        content = profile.read_text() if profile.exists() else ''
        receipt = state / (name + '.json')
        if not receipt.exists():
            jobs.atomic_json(receipt, {'existed': profile.exists(),
                                      'separator': bool(content and not content.endswith('\n'))})
            if profile.exists():
                backup = state / (name + '.backup')
                backup.write_bytes(profile.read_bytes())
                backup.chmod(0o600)
        content = strip_block(content)
        profile.write_text(content + ('\n' if content and not content.endswith('\n') else '') + block)
    print('Build entrypoints installed for new zsh and bash shells.')


def uninstall_shell():
    home = home_path()
    state = home / 'state' / 'coverage-shell'
    for name in SHELLS:
        profile = Path.home() / name
        receipt = state / (name + '.json')
        if not receipt.exists() or not profile.exists() or profile.is_symlink():
            continue
        info = json.loads(receipt.read_text())
        content = strip_block(profile.read_text())
        if info.get('separator') and content.endswith('\n'):
            backup = state / (name + '.backup')
            if backup.exists() and content == backup.read_text() + '\n':
                content = content[:-1]
        if not content and not info['existed']:
            profile.unlink()
        else:
            profile.write_text(content)
        receipt.unlink()
    shims = home / 'shims'
    if shims.exists() and not shims.is_symlink():
        for name in TOOLS:
            path = shims / name
            if path.is_file() and not path.is_symlink() and 'coverage.py' in path.read_text():
                path.unlink()
        try:
            shims.rmdir()
        except OSError:
            pass  # Preserve anything not generated by this installer.


def owned_json(path, private=False):
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor) as stream:
        info = os.fstat(stream.fileno())
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                or info.st_mode & (0o077 if private else 0o022) or info.st_size > 1024 * 1024):
            raise ValueError('unsafe coverage evidence')
        return json.load(stream)


def covered(home):
    """Join only the caller's actual live owned process group, never an env claim."""
    registry = home / 'guard-reservations'
    if not registry.exists():
        return False
    if registry.is_symlink():
        raise ValueError('unsafe reservation registry')
    group = os.getpgrp()
    session = os.getsid(0)
    for path in registry.glob('*.json'):
        if not re.fullmatch(r'[A-Za-z0-9_.-]{1,100}\.json', path.name):
            continue
        try:
            descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
            with os.fdopen(descriptor) as stream:
                info = os.fstat(stream.fileno())
                if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                        or info.st_mode & 0o022 or info.st_size > 1024 * 1024):
                    continue
                try:
                    fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    continue  # An unheld/stale record cannot cover anything.
                except BlockingIOError:
                    pass
                record = json.load(stream)
                controller = record.get('child')
                if record.get('state') != 'running' or type(controller) is not int:
                    continue
                # Original guard uses its session supervisor as record.child.
                if controller == group == session and os.getpgid(controller) == group:
                    return True
                # The pressure runtime places the command in its owned subgroup.
                runtime_path = path.with_suffix('.runtime')
                runtime_hint = record.get('runtime_file')
                if not isinstance(runtime_hint, str) or Path(runtime_hint).resolve(strict=True) != runtime_path.resolve(strict=True):
                    continue
                runtime = owned_json(runtime_path, private=True)
                if (runtime.get('job_id') == record.get('id')
                        and runtime.get('owner') == record.get('owner')
                        and runtime.get('command_hash') == record.get('command_hash')
                        and runtime.get('controller_pid') == controller
                        and runtime.get('runtime_group') == group
                        and session == group and os.getpgid(group) == group):
                    return True
        except (OSError, ValueError, TypeError, json.JSONDecodeError):
            continue  # Missing or ambiguous proof never grants a bypass.
    return False


def real_command(command, shim=False):
    if not command:
        raise ValueError('coverage requires a command')
    name = Path(command[0]).name if shim else command[0]
    if shim:
        directories = {(home_path() / 'shims').resolve()}
        if '/' in command[0]:
            directories.add(Path(command[0]).absolute().parent.resolve())
        path = ':'.join(entry for entry in os.environ.get('PATH', '').split(':')
                        if Path(entry or '.').resolve() not in directories)
        found = shutil.which(name, path=path)
    else:
        found = shutil.which(name)
    if not found:
        raise FileNotFoundError('build executable not found: ' + name)
    # Do not resolve rustup/toolchain proxy symlinks: executable basename matters.
    return [found, *command[1:]]


def execute(command, shim=False):
    command = real_command(command, shim=shim)
    # A new session cannot preserve a caller's controlling terminal/job control.
    # Keep interactive human invocations transparent and make no job claim.
    if any(os.isatty(descriptor) for descriptor in (0, 1, 2)):
        os.execvpe(command[0], command, os.environ)
    home = home_path()
    if covered(home):
        os.execvpe(command[0], command, os.environ)
    if os.environ.get('DISK_JANITOR_BROKER'):
        raise ValueError(os.environ['DISK_JANITOR_BROKER'] + ' already admitted this execution; no nested reservation was created')
    store = jobs.Store(home)
    meta = store.create(command, Path.cwd(), os.environ)
    directory = store.directory(meta['id'])
    # The foreground caller itself owns execution. Carry its lifetime lock across
    # exec into the same guard; observers never create or replay another worker.
    descriptor = os.open(directory / 'worker.lock', os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
    os.set_inheritable(descriptor, True)
    store.update(meta['id'], accepted=True, worker_pid=os.getpid(), output_mode='foreground')
    arguments = jobs.guard_command(store, meta)
    # Keep the ordinary accepted/cancel contract, but preserve the caller's
    # streams instead of requesting a detached bounded diagnostic log.
    start = arguments.index('--job-log-file')
    del arguments[start:start + 2]
    arguments.insert(arguments.index('--'), '--foreground-stdio')
    try:
        os.execvpe(arguments[0], arguments, os.environ)
    except OSError as error:
        store.update(meta['id'], state='failed', exit_code=126 if error.errno in (1, 13) else 127,
                     reason='foreground guard could not start')
        raise
    finally:
        os.close(descriptor)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('install-shell', 'uninstall-shell', 'exec', 'shim'))
    parser.add_argument('command', nargs=argparse.REMAINDER)
    args = parser.parse_args()
    try:
        if args.action == 'install-shell':
            install_shell()
        elif args.action == 'uninstall-shell':
            uninstall_shell()
        else:
            command = args.command[1:] if args.command[:1] == ['--'] else args.command
            execute(command, shim=args.action == 'shim')
        return 0
    except FileNotFoundError as error:
        print('disk-janitor: ' + str(error), file=sys.stderr)
        return 127
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print('disk-janitor: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
